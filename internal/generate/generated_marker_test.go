package generate

import "testing"

func TestGeneratedArtifactMarkerAfterBuildConstraint(t *testing.T) {
	const marker = "// Code generated by Scenery. DO NOT EDIT.\npackage main\n"
	for _, test := range []struct {
		name string
		text string
		want bool
	}{
		{"ordinary", marker, true},
		{"library-export", "//go:build scenery_library_export_maps3d\n\n" + marker, true},
		{"malformed-constraint", "//go:build (broken\n\n" + marker, false},
		{"unmarked", "//go:build scenery_library_export_maps3d\n\npackage main\n", false},
		{"marker-after-code", "//go:build scenery_library_export_maps3d\n\npackage main\n" + marker, false},
	} {
		t.Run(test.name, func(t *testing.T) {
			if got := trustedGeneratedArtifact("scenery.library-generated.json", "export/main.gen.go", []byte(test.text)); got != test.want {
				t.Fatalf("trustedGeneratedArtifact() = %v, want %v", got, test.want)
			}
		})
	}
}
