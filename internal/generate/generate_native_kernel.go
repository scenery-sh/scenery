package generate

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	appcfg "scenery.sh/internal/app"
	"scenery.sh/internal/codegen"
	"scenery.sh/internal/compiler"
)

// RenderNativeKernelWorkspaceFiles renders the initial unary feasibility
// kernel from the same compiled binding as its worker. This kernel has no
// imports of application packages. Broader transport mappings fail closed.
func RenderNativeKernelWorkspaceFiles(result *compiler.Result, cfg appcfg.Config, bindingAddress string) (map[string][]byte, error) {
	if result == nil || result.Manifest == nil || result.ContractStatus != "valid" {
		return nil, fmt.Errorf("native kernel requires a valid compiled contract")
	}
	resources := resourcesByAddress(result.Manifest)
	binding, exists := resources[bindingAddress]
	if !exists || stringValue(binding.Spec["protocol"]) != "http" || stringValue(binding.Spec["delivery"]) != "call" {
		return nil, fmt.Errorf("native kernel requires a unary HTTP binding")
	}
	operation, exists := resources[resolveResourceRef(binding, refString(binding.Spec["operation"]), "operation")]
	if !exists {
		return nil, fmt.Errorf("native kernel operation is missing")
	}
	if len(eventEmissionsForOperations(result.Manifest.Resources, []Resource{operation})) != 0 {
		return nil, fmt.Errorf("native kernel event emission is not implemented")
	}
	httpSpec, _ := binding.Spec["http"].(map[string]any)
	requestSchema, err := renderContractRequestSchema(resources, operation, binding, httpSpec)
	if err != nil {
		return nil, err
	}
	// Typed record/body codecs and output splits require further migration.
	if httpSpec["body"] != nil || len(namedChildren(httpSpec, "context")) != 0 {
		return nil, fmt.Errorf("native kernel experiment accepts scalar mapped inputs only")
	}
	responses := responseMappings(httpSpec)
	variants := namedChildren(operation.Spec, "result")
	if len(variants) != 1 || len(namedChildren(operation.Spec, "error")) != 0 || goWireTypeExpression(variants[0]["type"]) != "json" {
		return nil, fmt.Errorf("native kernel experiment requires one JSON result variant")
	}
	name := stringValue(variants[0]["name"])
	response := responses["result."+name]
	body, _ := response["body"].(map[string]any)
	if stringValue(body["codec"]) != "json" || refOrString(body["from"]) != "result."+name || len(namedChildren(response, "header")) != 0 || len(namedChildren(response, "cookie")) != 0 {
		return nil, fmt.Errorf("native kernel experiment requires an unsplit JSON result body")
	}
	status, err := strconv.Atoi(stringValue(response["status"]))
	if err != nil {
		return nil, err
	}
	service := resources[resolveResourceRef(operation, refString(operation.Spec["service"]), "service")]
	var source strings.Builder
	source.WriteString("// Code generated by Scenery. DO NOT EDIT.\npackage main\nimport(\n\"context\"\n\"encoding/json\"\n\"fmt\"\n\"io\"\n\"net/http\"\n\"os\"\nscenery \"scenery.sh\"\nsceneryruntime \"scenery.sh/runtime/host\"\n")
	if cfg.Auth.Enabled {
		source.WriteString("sceneryauth \"scenery.sh/auth\"\n")
	}
	source.WriteString(")\nfunc main(){ if err:=run();err!=nil{fmt.Fprintln(os.Stderr,err);os.Exit(1)} }\nfunc run()error{\n")
	fmt.Fprintf(&source, "if err:=sceneryruntime.VerifyLinkedContractBundle(%q);err!=nil{return err}\nif err:=json.NewEncoder(os.Stdout).Encode(struct{PID int; Bundle sceneryruntime.LinkedContractBundle}{os.Getpid(),sceneryruntime.CurrentLinkedContractBundle()});err!=nil{return err}\n", result.Manifest.ContractRevision)
	source.WriteString("var setup struct{ WorkerEndpoint string; WorkerToken string; WorkerInputDigest string; Listen string }\nif err:=json.NewDecoder(os.Stdin).Decode(&setup);err!=nil{return err}\ngo func(){_,_=io.Copy(io.Discard,os.Stdin);process,err:=os.FindProcess(os.Getpid());if err==nil{_=process.Signal(os.Interrupt)}}()\n")
	fmt.Fprintf(&source, "client,err:=sceneryruntime.NewNativeWorkerClient(setup.WorkerEndpoint,setup.WorkerToken,%q,setup.WorkerInputDigest);if err!=nil{return err};defer client.Close()\n", result.Manifest.ContractRevision)
	fmt.Fprintf(&source, "if err:=sceneryruntime.ConfigureSQLBindings(%s);err!=nil{return err}\n", codegen.SQLBindingsExpression(result.SQLRequirements))
	if cfg.Auth.Enabled {
		fmt.Fprintf(&source, "if err:=sceneryauth.RegisterStandard(%s);err!=nil{return err}\n", codegen.AuthConfigExpression(cfg.Auth))
	}
	fmt.Fprintf(&source, "if err:=sceneryruntime.RegisterEndpointChecked(&sceneryruntime.Endpoint{Service:%q,Name:%q,Access:%s,Path:%q,Methods:[]string{%q},ContractPolicy:%s,\n", service.Name, goName(binding.Name), runtimeAccess(binding), runtimeBindingPath(resources, binding, stringValue(httpSpec["path"])), stringValue(httpSpec["method"]), renderContractHTTPPolicy(resources, binding, httpSpec))
	fmt.Fprintf(&source, "DecodeContractRequest:func(request *http.Request,pathValues map[string]string)(sceneryruntime.ContractDecodedRequest,error){input,err:=sceneryruntime.DecodeContractInput[json.RawMessage](request,pathValues,%s);return sceneryruntime.ContractDecodedRequest{Payload:input},err},\n", requestSchema)
	fmt.Fprintf(&source, "Invoke:func(ctx context.Context,_ []any,payload any)(any,error){return client.Invoke(ctx,%q,payload.(json.RawMessage))},\n", operation.Address)
	source.WriteString("EncodeContractOutcome:func(request *http.Request,outcome any)(sceneryruntime.ContractHTTPResponse,error){ envelope,ok:=outcome.(json.RawMessage);if !ok{return sceneryruntime.ContractHTTPResponse{},fmt.Errorf(\"invalid native outcome\")};kind,name,payload,err:=scenery.DecodeContractOutcomeEnvelope(envelope);if err!=nil{return sceneryruntime.ContractHTTPResponse{},err};\n")
	fmt.Fprintf(&source, "if kind!=\"result\"||name!=%q{return sceneryruntime.ContractHTTPResponse{},fmt.Errorf(\"unexpected native outcome\")};return sceneryruntime.EncodeContractPreparedRepresentationWithOptions(request,%d,envelope,scenery.JSON(payload),\"json\",[]string{\"application/json\"},%s)},\n", name, status, renderContractResponseOptions(httpSpec, "json"))
	fmt.Fprintf(&source, "});err!=nil{return err}\nreturn sceneryruntime.Main(sceneryruntime.AppConfig{Name:%q,ListenAddr:setup.Listen})\n}\n", cfg.Name)
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format native kernel: %w", err)
	}
	return map[string][]byte{"scenery_framework_kernel/main.go": formatted}, nil
}
