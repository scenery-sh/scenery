// RenderNativeWorkerWorkspaceFiles renders the explicitly selected plan-0180
// additions to a fully prepared caller-owned workspace. It never publishes files, selects a
// runtime, or makes the experiment available through ordinary product commands.
// All native services/operations are retained, including unadmitted operations.
func RenderNativeWorkerWorkspaceFiles(result *compiler.Result, bindingAddress string) (map[string][]byte, error) {
	if result == nil || result.Manifest == nil || result.ContractStatus != "valid" {
		return nil, fmt.Errorf("native worker requires a valid compiled contract")
	}
	idx := newResourceIndex(result.Manifest.Resources)
	binding, exists := idx.byAddress[bindingAddress]
	if !exists || stringValue(binding.Spec["protocol"]) != "http" || stringValue(binding.Spec["delivery"]) != "call" {
		return nil, fmt.Errorf("native worker experiment requires an explicit unary HTTP binding")
	}
	operationAddress := resolveResourceRef(binding, refString(binding.Spec["operation"]), "operation")
	if operationAddress == "" {
		return nil, fmt.Errorf("native worker binding has no operation")
	}
	generatedRoot, generatedImport, err := resolveApplicationGeneratedRoot(result)
	if err != nil {
		return nil, err
	}
	adapters, err := cachedApplicationAdapters(newProjectionInput(result), generatedImport, func() ([]applicationAdapter, error) {
		return renderApplicationAdapters(result, idx, generatedImport)
	})
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	var required []string
	var main strings.Builder
	main.WriteString("// Code generated by Scenery. DO NOT EDIT.\npackage main\nimport (\n\"fmt\"\n\"os\"\nsceneryruntime \"scenery.sh/runtime/worker\"\n")
	found := false
	for i, adapter := range adapters {
		service := idx.byAddress[adapter.Address]
		if compiler.IsProviderCRUDService(service) {
			return nil, fmt.Errorf("native worker experiment has not converted provider CRUD service %s", service.Address)
		}
		operations := compiler.ServiceOperations(result.Manifest.Resources, service)
		bindings := serviceHTTPBindings(result.Manifest.Resources, operations)
		for _, operation := range operations {
			if operation.Address == operationAddress {
				found = true
			}
		}
		covered := append([]string{service.Address}, resourceAddresses(operations)...)
		required = append(required, covered...)
		source, err := renderWorkerAdapter(result, idx, adapter, service, operations, bindings, covered)
		if err != nil {
			return nil, err
		}
		relative, err := filepath.Rel(result.Root, filepath.Join(generatedRoot, "nativeworker", adapter.RelativeDir, "adapter.gen.go"))
		if err != nil || strings.HasPrefix(relative, "..") {
			return nil, fmt.Errorf("native worker generated root leaves the workspace")
		}
		files[filepath.ToSlash(relative)] = source
		fmt.Fprintf(&main, "adapter%d %q\n", i, generatedImport+"/nativeworker/"+adapter.RelativeDir)
	}
	if !found {
		return nil, fmt.Errorf("native worker selected operation is not native")
	}
	main.WriteString(")\nfunc main() {\n")
	fmt.Fprintf(&main, "err := sceneryruntime.Main(%q, %q, []sceneryruntime.Admission{{Operation:%q, Binding:%q}}, %s, func() error {\n", result.Manifest.Application.Name, result.Manifest.ContractRevision, operationAddress, bindingAddress, codegen.SQLBindingsExpression(result.SQLRequirements))
	fmt.Fprintf(&main, "registry, err := sceneryruntime.NewContractRegistry(sceneryruntime.ContractRegistryOptions{ContractRevision:%q, RequiredAddresses:%#v})\nif err != nil { return err }\n", result.Manifest.ContractRevision, canonicalStrings(required))
	for i := range adapters {
		fmt.Fprintf(&main, "if err := adapter%d.Register(registry); err != nil { return err }\n", i)
	}
	main.WriteString("return registry.Seal()\n})\nif err != nil { fmt.Fprintln(os.Stderr, err); os.Exit(1) }\n}\n")
	formatted, err := format.Source([]byte(main.String()))
	if err != nil {
		return nil, fmt.Errorf("format native worker entrypoint: %w", err)
	}
	files["scenery_native_worker/main.go"] = formatted
	return files, nil
}

func renderWorkerAdapter(result *compiler.Result, idx *resourceIndex, adapter applicationAdapter, service Resource, operations, bindings []Resource, covered []string) ([]byte, error) {
	b, err := renderNativeAdapterPreamble(result.Manifest.ContractRevision, adapter.PackageIdentity, adapter.PackageABI, adapter.Implementation, adapter.Contract, adapter.PackageName, service, operations, bindings, idx, "scenery.sh/runtime/worker", false)
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(b, "func Register(registry scenery.Registry) error { return registry.Register(%q, sceneryruntime.ContractRegistration{ContractRevision:ContractRevision, PackageContractABIRevision:PackageContractABIRevision, RuntimeABI:sceneryruntime.ContractRuntimeABI, CoveredAddresses:%#v, Apply:func() error {\n", service.Address+"/native-adapter", covered)
	b.WriteString("if contract.PackageIdentity != PackageIdentity || contract.PackageContractABIRevision != PackageContractABIRevision { return fmt.Errorf(\"native package ABI mismatch\") }\n")
	if err := renderNativeServiceInitialization(b, idx, service); err != nil {
		return nil, err
	}
	for _, operation := range operations {
		name := goName(operation.Name)
		handler, _ := operation.Spec["handler"].(map[string]any)
		method := stringValue(handler["method"])
		streaming := operationUsesHTTPStream(operation, bindings)
		fmt.Fprintf(b, "if err := sceneryruntime.RegisterOperation(sceneryruntime.Operation{Address:%q, Service:%q, Streaming:%t,\n", operation.Address, service.Address, streaming)
		fmt.Fprintf(b, "Decode:func(data []byte)(any,error){ return contract.Unmarshal%sInput(data) },\n", name)
		fmt.Fprintf(b, "Encode:func(value any)([]byte,error){ typed, ok := value.(contract.%sOutcome); if !ok { return nil, fmt.Errorf(\"native outcome has type %%T\",value) }; return contract.Marshal%sOutcome(typed) },\n", name, name)
		fmt.Fprintf(b, "Invoke:func(ctx context.Context,input any)(any,scenery.ByteStream,error){ typed,ok:=input.(contract.%sInput); if !ok { return nil,scenery.ByteStream{},fmt.Errorf(\"native input has type %%T\",input) }; copied,err:=contract.Clone%sInput(typed); if err != nil { return nil,scenery.ByteStream{},err };\n", name, name)
		if streaming {
			fmt.Fprintf(b, "outcome,stream,err:=service.%s(ctx,copied);\n", method)
		} else {
			fmt.Fprintf(b, "outcome,err:=service.%s(ctx,copied); stream:=scenery.ByteStream{};\n", method)
		}
		b.WriteString("if err != nil { _=stream.Close(); if outcome != nil { return nil,scenery.ByteStream{},fmt.Errorf(\"handler returned outcome and error\") }; return nil,scenery.ByteStream{},err }; if outcome == nil { _=stream.Close(); return nil,scenery.ByteStream{},fmt.Errorf(\"handler returned nil outcome without error\") };\n")
		fmt.Fprintf(b, "cloned,err:=contract.Clone%sOutcome(outcome); if err != nil { _=stream.Close(); return nil,scenery.ByteStream{},err }; return cloned,stream,nil },\n}); err != nil { return err }\n", name)
	}
	b.WriteString("return nil\n}})\n}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format native worker adapter %s: %w", service.Address, err)
	}
	return formatted, nil
}
