package generate

import (
	"fmt"
	"path/filepath"
	"strings"

	"scenery.sh/internal/appconfig"
)

// renderTypeScriptPublicConfig renders the typed projection of the
// application's public configuration inputs, or nothing when it has none.
// Values are served by the runtime per configuration revision, so a changed
// value never requires rebuilding the frontend bundle.
func renderTypeScriptPublicConfig(result *Result, root string) (*generatedFile, error) {
	catalog, err := appconfig.BuildCatalog(result.Manifest, appconfig.FrameworkOptions{})
	if err != nil {
		return nil, err
	}
	var fields []string
	for _, input := range catalog.Inputs {
		if !input.Public {
			continue
		}
		fields = append(fields, fmt.Sprintf("  readonly %q?: %s;", input.Key, publicConfigTSType(input.Type)))
	}
	if len(fields) == 0 {
		return nil, nil
	}
	var b strings.Builder
	b.WriteString("// Code generated by Scenery. DO NOT EDIT.\n\n")
	b.WriteString("/** Public configuration inputs of the selected environment. An unconfigured optional input is absent. */\n")
	b.WriteString("export interface PublicConfig {\n" + strings.Join(fields, "\n") + "\n}\n\n")
	b.WriteString(`/** The runtime's public configuration, pinned to one configuration revision. */
export interface PublicConfigDocument {
  readonly kind: "scenery.public-config";
  readonly revision: string;
  readonly values: PublicConfig;
}

export interface LoadPublicConfigOptions {
  readonly fetch?: typeof fetch;
  readonly signal?: AbortSignal;
}

/** Loads the public configuration served at the API base URL. */
export async function loadPublicConfig(apiBaseUrl: string, options: LoadPublicConfigOptions = {}): Promise<PublicConfigDocument> {
  const fetcher = options.fetch ?? fetch;
  const base = apiBaseUrl.endsWith("/") ? apiBaseUrl : apiBaseUrl + "/";
  const response = await fetcher(new URL("__scenery/public-config", base), {
    method: "GET",
    headers: { accept: "application/json" },
    credentials: "same-origin",
    signal: options.signal,
  });
  if (!response.ok) {
    throw new Error("public configuration request failed with status " + response.status);
  }
  const document: unknown = await response.json();
  if (
    typeof document !== "object" || document === null ||
    (document as { kind?: unknown }).kind !== "scenery.public-config" ||
    typeof (document as { revision?: unknown }).revision !== "string" ||
    typeof (document as { values?: unknown }).values !== "object" || (document as { values?: unknown }).values === null
  ) {
    throw new Error("public configuration response is malformed");
  }
  return document as PublicConfigDocument;
}
`)
	return &generatedFile{Path: filepath.Join(root, "public-config.ts"), Bytes: []byte(b.String())}, nil
}

func publicConfigTSType(typeExpression string) string {
	typeExpression = strings.TrimSpace(typeExpression)
	for _, wrapper := range []string{"optional(", "nullable("} {
		if strings.HasPrefix(typeExpression, wrapper) && strings.HasSuffix(typeExpression, ")") {
			typeExpression = strings.TrimSpace(typeExpression[len(wrapper) : len(typeExpression)-1])
		}
	}
	for _, wrapper := range []string{"list(", "set("} {
		if strings.HasPrefix(typeExpression, wrapper) && strings.HasSuffix(typeExpression, ")") {
			return "ReadonlyArray<" + publicConfigTSType(typeExpression[len(wrapper):len(typeExpression)-1]) + ">"
		}
	}
	switch typeExpression {
	case "bool":
		return "boolean"
	case "int32", "uint32", "float32", "float64":
		return "number"
	default:
		return "string"
	}
}
