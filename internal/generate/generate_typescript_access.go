package generate

func renderReactAccessAdapter() string {
	return `// Code generated by Scenery. DO NOT EDIT.
import {
  createContext,
  createElement,
  useContext,
  type ComponentType,
  type ReactNode,
} from "react";
import type {
  SceneryRouteDescriptor,
  SceneryRouteParams,
} from "./routes.generated.js";
import type { SceneryAccessMetadata } from "./routes.generated.js";

export type SceneryAccessTarget =
  | {
      readonly kind: "route";
      readonly route: SceneryRouteDescriptor;
    }
  | {
      readonly kind: "workspace-tab";
      readonly route: SceneryRouteDescriptor;
      readonly name: string;
      readonly label: string;
      readonly applicationKey?: string;
      readonly accessKey?: string;
    };

export type SceneryAccessResult =
  | { readonly status: "allowed" }
  | { readonly status: "pending" }
  | {
      readonly status: "denied";
      readonly reason?: string;
      readonly redirectTo?: string;
    };

export type SceneryAccessResolver = (
  target: SceneryAccessTarget,
  currentPath: string,
) => SceneryAccessResult;

export type SceneryAccessContextValue = {
  readonly routes: readonly SceneryRouteDescriptor[];
  readonly currentRoute: SceneryRouteDescriptor | undefined;
  readonly currentPath: string;
  readonly resolveAccess: SceneryAccessResolver | undefined;
  readonly accessPending: ReactNode | undefined;
  readonly accessDenied:
    | ((props: {
        readonly target: SceneryAccessTarget;
        readonly result: Extract<SceneryAccessResult, { readonly status: "denied" }>;
      }) => ReactNode)
    | undefined;
};

const SceneryAccessContext = createContext<SceneryAccessContextValue>({
  routes: [],
  currentRoute: undefined,
  currentPath: "/",
  resolveAccess: undefined,
  accessPending: undefined,
  accessDenied: undefined,
});

export function SceneryAccessProvider({
  value,
  children,
}: {
  readonly value: SceneryAccessContextValue;
  readonly children: ReactNode;
}) {
  return createElement(SceneryAccessContext.Provider, { value }, children);
}

export function useSceneryAccess(): SceneryAccessContextValue {
  return useContext(SceneryAccessContext);
}

export function resolveSceneryAccess(
  context: SceneryAccessContextValue,
  target: SceneryAccessTarget,
): SceneryAccessResult {
  return context.resolveAccess?.(target, context.currentPath) ?? { status: "allowed" };
}

export function renderSceneryAccessDenied(
  context: SceneryAccessContextValue,
  target: SceneryAccessTarget,
  result: Extract<SceneryAccessResult, { readonly status: "denied" }>,
): ReactNode {
  if (context.accessDenied) return context.accessDenied({ target, result });
  return createElement(
    "div",
    { role: "alert" },
    result.reason ?? "You do not have access to this page.",
  );
}

export function SceneryRouteAccessBoundary({
  route,
  params,
  renderRedirect,
}: {
  readonly route: SceneryRouteDescriptor;
  readonly params: SceneryRouteParams;
  readonly renderRedirect: (to: string) => ReactNode;
}) {
  const context = useSceneryAccess();
  const target = { kind: "route", route } as const satisfies SceneryAccessTarget;
  const result = resolveSceneryAccess(context, target);
  if (result.status === "pending") return context.accessPending ?? null;
  if (result.status === "denied") {
    if (result.redirectTo) return renderRedirect(result.redirectTo);
    return renderSceneryAccessDenied(context, target, result);
  }
  return createElement(
    route.component as ComponentType<{ readonly params?: SceneryRouteParams }>,
    { params },
  );
}

export function resolveSceneryWorkspaceAccess<
  Tab extends SceneryAccessMetadata & {
    readonly name: string;
    readonly label: string;
  },
>(
  context: SceneryAccessContextValue,
  tabs: readonly Tab[],
): { readonly tabs: readonly Tab[]; readonly emptyState: ReactNode | undefined } {
  if (!context.resolveAccess || !context.currentRoute) {
    return { tabs, emptyState: undefined };
  }
  const decisions = tabs.map((tab) => {
    const target = {
      kind: "workspace-tab",
      route: context.currentRoute as SceneryRouteDescriptor,
      name: tab.name,
      label: tab.label,
      applicationKey: tab.applicationKey,
      accessKey: tab.accessKey,
    } as const satisfies SceneryAccessTarget;
    return { tab, target, result: resolveSceneryAccess(context, target) };
  });
  const visible = decisions
    .filter(({ result }) => result.status === "allowed")
    .map(({ tab }) => tab);
  if (visible.length > 0) return { tabs: visible, emptyState: undefined };
  if (decisions.some(({ result }) => result.status === "pending")) {
    return { tabs: visible, emptyState: context.accessPending ?? null };
  }
  const denied = decisions.find(
    (decision): decision is typeof decision & {
      readonly result: Extract<SceneryAccessResult, { readonly status: "denied" }>;
    } => decision.result.status === "denied",
  );
  return {
    tabs: visible,
    emptyState: denied
      ? renderSceneryAccessDenied(context, denied.target, denied.result)
      : undefined,
  };
}
`
}
