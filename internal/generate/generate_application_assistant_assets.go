package generate

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"path/filepath"
	"sort"
	"strings"

	generateapi "scenery.sh/internal/generate/api"
	"scenery.sh/internal/runtimeassets"
)

type AssistantAssetDescriptor = generateapi.AssistantAssetDescriptor
type AssistantAssetInput = generateapi.AssistantAssetInput

const (
	AssistantAssetDescriptorKind   = generateapi.AssistantAssetDescriptorKind
	AssistantAssetCapsuleEntry     = generateapi.AssistantAssetCapsuleEntry
	assistantAssetsPackageRelative = "internal/scenerygen/assets"
)

var AssistantAssetSchemaRevision = runtimeassets.AssistantAssetSchemaRevision

// RenderAssistantAssetRegistry renders the generated Go package and its
// content-addressed archive/descriptor files.  The returned paths are
// workspace-relative and can be written as one artifact-set transaction by
// the build orchestrator.  Every byte is derived from the supplied immutable
// input; map iteration order never affects the output.
func RenderAssistantAssetRegistry(result *Result, inputs []AssistantAssetInput) (map[string][]byte, error) {
	if result == nil || result.Manifest == nil {
		return nil, fmt.Errorf("valid compiler result is required")
	}
	root, _, err := resolveApplicationGeneratedRoot(result)
	if err != nil {
		return nil, err
	}
	relativeRoot, err := filepath.Rel(result.Root, filepath.Join(root, filepath.FromSlash("assets")))
	if err != nil || relativeRoot == ".." || strings.HasPrefix(relativeRoot, ".."+string(filepath.Separator)) {
		return nil, fmt.Errorf("assistant asset package escapes application root")
	}
	relativeRoot = filepath.ToSlash(relativeRoot)

	ordered := append([]AssistantAssetInput(nil), inputs...)
	for index := range ordered {
		if err := validateAssistantAssetInput(&ordered[index]); err != nil {
			return nil, err
		}
	}
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].Descriptor.AssistantAddress != ordered[j].Descriptor.AssistantAddress {
			return ordered[i].Descriptor.AssistantAddress < ordered[j].Descriptor.AssistantAddress
		}
		return ordered[i].Descriptor.Target < ordered[j].Descriptor.Target
	})
	for index := 1; index < len(ordered); index++ {
		if ordered[index-1].Descriptor.AssistantAddress == ordered[index].Descriptor.AssistantAddress && ordered[index-1].Descriptor.Target == ordered[index].Descriptor.Target {
			return nil, fmt.Errorf("duplicate assistant asset %s for target %s", ordered[index].Descriptor.AssistantAddress, ordered[index].Descriptor.Target)
		}
	}

	files := make(map[string][]byte, len(ordered)*5+1)
	nodeFiles := map[string]string{}
	descriptorFiles := map[string]string{}
	nodeTreeDescriptorFiles := map[string]string{}
	capsuleTreeDescriptorFiles := map[string]string{}
	var source strings.Builder
	source.WriteString("// Code generated by Scenery. DO NOT EDIT.\npackage assets\n\n")
	source.WriteString("import _ \"embed\"\n\n")
	source.WriteString("// Descriptor is the provider-neutral production asset identity.\n")
	source.WriteString("type Descriptor struct {\n")
	source.WriteString("\tKind string `json:\"kind\"`\n\tSchemaRevision string `json:\"schema_revision\"`\n")
	source.WriteString("\tAssistantAddress string `json:\"assistant_address\"`\n\tTarget string `json:\"target\"`\n")
	source.WriteString("\tRuntimeRevision string `json:\"runtime_revision\"`\n\tCapabilityRevision string `json:\"capability_revision\"`\n")
	source.WriteString("\tNodeArchiveDigest string `json:\"node_archive_digest\"`\n\tNodeTreeDigest string `json:\"node_tree_digest\"`\n")
	source.WriteString("\tCapsuleArchiveDigest string `json:\"capsule_archive_digest\"`\n\tCapsuleTreeDigest string `json:\"capsule_tree_digest\"`\n")
	source.WriteString("\tCapsuleEntry string `json:\"capsule_entry\"`\n\tPackageLockDigest string `json:\"package_lock_digest\"`\n}\n\n")
	source.WriteString("type Asset struct { Descriptor Descriptor; DescriptorJSON []byte; NodeArchive []byte; NodeDescriptorJSON []byte; CapsuleArchive []byte; CapsuleDescriptorJSON []byte }\n\n")

	for index, input := range ordered {
		descriptor := input.Descriptor
		key := digestKey(descriptor.CapsuleArchiveDigest)
		if key == "" {
			key = fmt.Sprintf("asset-%d", index)
		}
		nodeKey := digestKey(descriptor.NodeArchiveDigest)
		nodePath := "archives/node-" + nodeKey + ".tar.gz"
		if previous, exists := nodeFiles[nodeKey]; exists {
			nodePath = previous
		} else {
			nodeFiles[nodeKey] = nodePath
			files[filepath.ToSlash(filepath.Join(relativeRoot, filepath.FromSlash(nodePath)))] = append([]byte(nil), input.NodeArchive...)
		}
		descriptorPath := "descriptors/" + key + ".json"
		if previous, exists := descriptorFiles[key]; exists {
			descriptorPath = previous
		} else {
			descriptorFiles[key] = descriptorPath
			encoded, marshalErr := json.Marshal(descriptor)
			if marshalErr != nil {
				return nil, fmt.Errorf("marshal assistant asset descriptor: %w", marshalErr)
			}
			files[filepath.ToSlash(filepath.Join(relativeRoot, filepath.FromSlash(descriptorPath)))] = append(encoded, '\n')
		}
		nodeTreeKey := digestKey(descriptor.NodeTreeDigest)
		nodeDescriptorPath := "descriptors/node-tree-" + nodeTreeKey + ".json"
		if previous, exists := nodeTreeDescriptorFiles[nodeTreeKey]; exists {
			nodeDescriptorPath = previous
		} else {
			nodeTreeDescriptorFiles[nodeTreeKey] = nodeDescriptorPath
			files[filepath.ToSlash(filepath.Join(relativeRoot, filepath.FromSlash(nodeDescriptorPath)))] = append([]byte(nil), input.NodeDescriptorJSON...)
		}
		capsuleTreeKey := digestKey(descriptor.CapsuleTreeDigest)
		capsuleDescriptorPath := "descriptors/capsule-tree-" + capsuleTreeKey + ".json"
		if previous, exists := capsuleTreeDescriptorFiles[capsuleTreeKey]; exists {
			capsuleDescriptorPath = previous
		} else {
			capsuleTreeDescriptorFiles[capsuleTreeKey] = capsuleDescriptorPath
			files[filepath.ToSlash(filepath.Join(relativeRoot, filepath.FromSlash(capsuleDescriptorPath)))] = append([]byte(nil), input.CapsuleDescriptorJSON...)
		}
		capsulePath := "archives/capsule-" + key + ".tar.gz"
		files[filepath.ToSlash(filepath.Join(relativeRoot, filepath.FromSlash(capsulePath)))] = append([]byte(nil), input.CapsuleArchive...)

		varName := "descriptor_" + key
		nodeVar := "nodeArchive_" + nodeKey
		capsuleVar := "capsuleArchive_" + key
		descVar := "descriptorJSON_" + key
		nodeDescriptorVar := "nodeDescriptorJSON_" + nodeTreeKey
		capsuleDescriptorVar := "capsuleDescriptorJSON_" + capsuleTreeKey
		fmt.Fprintf(&source, "//go:embed %s\nvar %s []byte\n", filepath.ToSlash(descriptorPath), descVar)
		fmt.Fprintf(&source, "//go:embed %s\nvar %s []byte\n", filepath.ToSlash(nodePath), nodeVar)
		fmt.Fprintf(&source, "//go:embed %s\nvar %s []byte\n\n", filepath.ToSlash(capsulePath), capsuleVar)
		fmt.Fprintf(&source, "//go:embed %s\nvar %s []byte\n", filepath.ToSlash(nodeDescriptorPath), nodeDescriptorVar)
		fmt.Fprintf(&source, "//go:embed %s\nvar %s []byte\n\n", filepath.ToSlash(capsuleDescriptorPath), capsuleDescriptorVar)
		fmt.Fprintf(&source, "var %s = Descriptor{Kind: %q, SchemaRevision: %q, AssistantAddress: %q, Target: %q, RuntimeRevision: %q, CapabilityRevision: %q, NodeArchiveDigest: %q, NodeTreeDigest: %q, CapsuleArchiveDigest: %q, CapsuleTreeDigest: %q, CapsuleEntry: %q, PackageLockDigest: %q}\n\n", varName, descriptor.Kind, descriptor.SchemaRevision, descriptor.AssistantAddress, descriptor.Target, descriptor.RuntimeRevision, descriptor.CapabilityRevision, descriptor.NodeArchiveDigest, descriptor.NodeTreeDigest, descriptor.CapsuleArchiveDigest, descriptor.CapsuleTreeDigest, descriptor.CapsuleEntry, descriptor.PackageLockDigest)
	}

	source.WriteString("var registry = []Asset{\n")
	for _, input := range ordered {
		descriptor := input.Descriptor
		key := digestKey(descriptor.CapsuleArchiveDigest)
		nodeKey := digestKey(descriptor.NodeArchiveDigest)
		nodeTreeKey := digestKey(descriptor.NodeTreeDigest)
		capsuleTreeKey := digestKey(descriptor.CapsuleTreeDigest)
		fmt.Fprintf(&source, "{Descriptor: descriptor_%s, DescriptorJSON: descriptorJSON_%s, NodeArchive: nodeArchive_%s, NodeDescriptorJSON: nodeDescriptorJSON_%s, CapsuleArchive: capsuleArchive_%s, CapsuleDescriptorJSON: capsuleDescriptorJSON_%s},\n", key, key, nodeKey, nodeTreeKey, key, capsuleTreeKey)
	}
	source.WriteString("}\n\nfunc Assets() []Asset { return append([]Asset(nil), registry...) }\n\nfunc Lookup(assistantAddress, target string) (Asset, bool) {\n\tfor _, asset := range registry { if asset.Descriptor.AssistantAddress == assistantAddress && asset.Descriptor.Target == target { return asset, true } }\n\treturn Asset{}, false\n}\n")
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated assistant asset registry: %w", err)
	}
	files[filepath.ToSlash(filepath.Join(relativeRoot, "assets.gen.go"))] = formatted
	return files, nil
}

func validateAssistantAssetInput(input *AssistantAssetInput) error {
	if input == nil {
		return fmt.Errorf("nil assistant asset input")
	}
	d := input.Descriptor
	if d.Kind != AssistantAssetDescriptorKind || d.SchemaRevision != AssistantAssetSchemaRevision {
		return fmt.Errorf("unsupported assistant asset descriptor identity")
	}
	for name, value := range map[string]string{
		"assistant_address": d.AssistantAddress, "target": d.Target,
		"runtime_revision": d.RuntimeRevision, "capability_revision": d.CapabilityRevision,
		"node_archive_digest": d.NodeArchiveDigest, "node_tree_digest": d.NodeTreeDigest,
		"capsule_archive_digest": d.CapsuleArchiveDigest, "capsule_tree_digest": d.CapsuleTreeDigest,
		"capsule_entry": d.CapsuleEntry, "package_lock_digest": d.PackageLockDigest,
	} {
		if strings.TrimSpace(value) == "" {
			return fmt.Errorf("assistant asset descriptor %s is required", name)
		}
	}
	if d.CapsuleEntry != AssistantAssetCapsuleEntry {
		return fmt.Errorf("assistant asset capsule_entry must be %q", AssistantAssetCapsuleEntry)
	}
	for name, data := range map[string][]byte{"node archive": input.NodeArchive, "capsule archive": input.CapsuleArchive} {
		sum := sha256.Sum256(data)
		want := "sha256:" + hex.EncodeToString(sum[:])
		var got string
		if name == "node archive" {
			got = d.NodeArchiveDigest
		} else {
			got = d.CapsuleArchiveDigest
		}
		if len(data) == 0 || got != want {
			return fmt.Errorf("assistant %s digest mismatch", name)
		}
	}
	if _, err := validateRuntimeAssetDescriptorJSON(input.NodeDescriptorJSON, d.NodeTreeDigest, "node"); err != nil {
		return err
	}
	if _, err := validateRuntimeAssetDescriptorJSON(input.CapsuleDescriptorJSON, d.CapsuleTreeDigest, "capsule"); err != nil {
		return err
	}
	if strings.Contains(strings.ToLower(d.AssistantAddress), "eve") || strings.Contains(strings.ToLower(d.Target), "eve") {
		return fmt.Errorf("assistant asset descriptor contains forbidden provider token")
	}
	return nil
}

func validateRuntimeAssetDescriptorJSON(data []byte, wantDigest, label string) ([]byte, error) {
	if len(data) == 0 {
		return nil, fmt.Errorf("assistant %s tree descriptor is required", label)
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	var descriptor runtimeassets.Descriptor
	if err := decoder.Decode(&descriptor); err != nil {
		return nil, fmt.Errorf("assistant %s tree descriptor is invalid: %w", label, err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		if err == nil {
			return nil, fmt.Errorf("assistant %s tree descriptor has trailing JSON", label)
		}
		return nil, fmt.Errorf("assistant %s tree descriptor has trailing data: %w", label, err)
	}
	if err := descriptor.Validate(); err != nil {
		return nil, fmt.Errorf("assistant %s tree descriptor failed validation: %w", label, err)
	}
	if descriptor.Digest != wantDigest {
		return nil, fmt.Errorf("assistant %s tree descriptor digest %s does not match simplified digest %s", label, descriptor.Digest, wantDigest)
	}
	canonical, err := json.Marshal(descriptor)
	if err != nil {
		return nil, fmt.Errorf("marshal assistant %s tree descriptor: %w", label, err)
	}
	if !bytes.Equal(data, canonical) {
		return nil, fmt.Errorf("assistant %s tree descriptor is not canonical JSON", label)
	}
	return canonical, nil
}

func digestKey(digest string) string {
	return strings.TrimPrefix(strings.TrimSpace(digest), "sha256:")
}
