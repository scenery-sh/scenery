package generate

import (
	"os"
	"strings"
	"testing"
)

// TestRustPreservingRecordMatchesSDKFixture pins the generated code for a
// record with unknown_fields = "preserve" to the copy the Rust SDK compiles
// and runs against the shared wire corpus.
func TestRustPreservingRecordMatchesSDKFixture(t *testing.T) {
	t.Parallel()
	record := Resource{Address: "probe/record/note", Module: "probe", Name: "note", Kind: "scenery.record", Spec: map[string]any{
		"unknown_fields": "preserve",
		"field": []any{
			map[string]any{"name": "text", "type": "string"},
			map[string]any{"name": "note", "type": "optional(nullable(string))"},
			map[string]any{"name": "ratio", "type": "optional(float64)"},
		},
	}}
	var source strings.Builder
	if err := (rustContractProjection{module: "probe", types: map[string]Resource{}}).renderType(&source, record); err != nil {
		t.Fatal(err)
	}
	fixture, err := os.ReadFile("../../sdk/rust/scenery-sdk/tests/preserved_record.rs.inc")
	if err != nil {
		t.Fatal(err)
	}
	if got := "// Generated by internal/generate for probe/record/note.\n" + source.String(); string(fixture) != got {
		t.Fatalf("SDK fixture differs from the generated record:\n%s", got)
	}
}
